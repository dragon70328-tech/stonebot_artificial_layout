def write_dxf() -> None:
    doc = ezdxf.new("R2000")
    doc.units = units.MM
    doc.header["$DWGCODEPAGE"] = "ANSI_936"
    msp = doc.modelspace()
    # 中文字体：默认 Standard 样式换成宋体，避免 CAD 里显示成问号
    for style_name in ("Standard",):
        style = doc.styles.get(style_name)
        style.dxf.font = "SimSun.ttf"
        style.dxf.bigfont = ""
    doc.layers.add("SPEC_PANEL", color=7, linetype="CONTINUOUS")
    doc.layers.add("ROOM_TEXT", color=7, linetype="CONTINUOUS")
    doc.layers.add("PANEL_ID", color=8, linetype="CONTINUOUS")

    for item in PANELS:
        if not item.get("draw", True):
            continue
        x0, y0, x1, y1 = item["rect"]
        if x1 <= x0 or y1 <= y0:
            continue
        msp.add_lwpolyline(
            [(x0, y0), (x1, y0), (x1, y1), (x0, y1)],
            close=True,
            dxfattribs={"layer": "SPEC_PANEL", "color": 7},
        )
        width, height = x1 - x0, y1 - y0
        if min(width, height) >= 200:
            label = msp.add_text(
                item["id"],
                dxfattribs={
                    "layer": "PANEL_ID",
                    "color": 8,
                    "height": 45,
                    "style": "Standard",
                },
            )
            label.set_placement(
                ((x0 + x1) / 2, (y0 + y1) / 2),
                align=TextEntityAlignment.MIDDLE_CENTER,
            )

    for text_value, x, y in ROOM_LABELS:
        entity = msp.add_text(
            text_value,
            dxfattribs={
                "layer": "ROOM_TEXT",
                "color": 7,
                "height": 90,
                "style": "Standard",
            },
        )
        entity.set_placement((x, y), align=TextEntityAlignment.BOTTOM_LEFT)

    # 凹槽内壁 8 件：图下列表（投影只有18宽，不画矩形）
    schedule = [
        "43楼 过道造型墙面 凹槽内壁规格板（共8件，厚18）",
        "侧板 110×700 ×2",
        "上口板 110×1169 ×3",
        "下口板 110×1169 ×3",
    ]
    for index, value in enumerate(schedule):
        entity = msp.add_text(
            value,
            dxfattribs={
                "layer": "ROOM_TEXT",
                "color": 7,
                "height": 80 if index else 90,
                "style": "Standard",
            },
        )
        entity.set_placement(
            (18897.7, -1700 - index * 160),
            align=TextEntityAlignment.BOTTOM_LEFT,
        )

    # 43楼客用卫生间 C 壁龛：直接标注背板/侧板/层板
    for value, x, y in [
        ("背板", 33009, -201),
        ("侧板", 32557, -201),
        ("侧板", 33461, -201),
        ("层板", 33510, 700),
        ("层板", 33510, 320),
    ]:
        entity = msp.add_text(
            value,
            dxfattribs={
                "layer": "PANEL_ID",
                "color": 8,
                "height": 60,
                "style": "Standard",
            },
        )
        entity.set_placement((x, y), align=TextEntityAlignment.MIDDLE_CENTER)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    doc.saveas(str(DXF_PATH), encoding="gbk")
    DXF_PATH.write_bytes(
        DXF_PATH.read_bytes().replace(b"ANSI_1252", b"ANSI_936")
    )


def write_excel() -> None:
    headers = [
        "编号", "房间/位置", "材料", "长(mm)", "宽(mm)", "厚(mm)",
        "数量", "面积(m²)", "磨边/边部做法", "备注", "确认度",
    ]
    rows: list[list] = [headers]
    total = 0.0
    for item in PANELS:
        area = item["length"] * item["width"] / 1_000_000.0
        total += area
        rows.append(
            [
                item["id"], item["room"], item["material"],
                item["length"], item["width"], item["thickness"], 1,
                round(area, 4), item["edge"], item["note"],
                item["confidence"],
            ]
        )
    rows.append(
        ["合计", "", "", "", "", "", len(PANELS), round(total, 4), "", "", ""]
    )
    write_xlsx(XLSX_PATH, rows, sheet_name="加工清单", decimal_columns=(8,))


def main() -> None:
    build()
    write_dxf()
    write_excel()
    print(f"dxf:  {DXF_PATH}")
    print(f"xlsx: {XLSX_PATH}")
    print(f"panels: {len(PANELS)}")
    pending = sum(1 for p in PANELS if p["confidence"] == "待确认")
    print(f"pending: {pending}")


if __name__ == "__main__":
    main()
